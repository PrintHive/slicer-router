/// Config lines copied from a PrusaSlicer 2.5.2 project: the model is `MK3MMU2`
/// and `printer_vendor` is empty, but `printer_notes` carries the vendor marker.
const PRUSA_252_CONFIG: &str = "; generated by PrusaSlicer 2.5.2+win64 on 2025-04-19 at 01:09:42 UTC\n\n\
    ; print_settings_id = 0.20mm QUALITY @MK3\n; printer_model = MK3MMU2\n\
    ; printer_notes = Don't remove the following keywords!\\nPRINTER_VENDOR_PRUSA3D\\nPRINTER_MODEL_MK3\\n\n\
    ; printer_settings_id = %NAME%\n; printer_technology = FFF\n; printer_vendor =\n";

#[test]
fn prusaslicer_252_config_layout_is_attributed_by_preset_name() {
    let verdict = detect_fixture(
        ThreeMf::new().model(Some("PrusaSlicer-2.5.2+win64")).entry(
            "Metadata/Slic3r_PE.config",
            PRUSA_252_CONFIG
                .replace("%NAME%", "Original Prusa i3 MK3 MMU2")
                .into_bytes(),
        ),
    );
    assert_verdict(&verdict, Some(Slicer::PrusaSlicer), Rule::PrinterProfile);
    assert_eq!(verdict.evidence.printer.vendor.as_deref(), Some("PRUSA3D"));
}

