//! Builds small `.3mf` archives for tests.

use std::fs::File;
use std::io::Write;
use std::path::{Path, PathBuf};

use zip::write::SimpleFileOptions;
use zip::{CompressionMethod, ZipWriter};

#[derive(Default)]
pub struct ThreeMf {
    entries: Vec<(String, Vec<u8>, CompressionMethod)>,
}

impl ThreeMf {
    pub fn new() -> Self {
        Self::default()
    }

    /// `3D/3dmodel.model` with an optional `Application` tag ahead of the geometry.
    pub fn model(self, application: Option<&str>) -> Self {
        self.model_with_geometry(application, "<object id=\"1\" type=\"model\"/>")
    }

    pub fn model_with_geometry(self, application: Option<&str>, geometry: &str) -> Self {
        let application = application
            .map(|a| format!("<metadata name=\"Application\">{a}</metadata>\n"))
            .unwrap_or_default();
        let xml = format!(
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<model unit=\"millimeter\" xml:lang=\"en-US\" \
             xmlns=\"http://schemas.microsoft.com/3dmanufacturing/core/2015/02\">\n \
             <metadata name=\"Title\">fixture</metadata>\n{application}\
             <resources>\n{geometry}\n</resources>\n<build/>\n</model>\n"
        );
        self.entry("3D/3dmodel.model", xml.into_bytes())
    }

    /// `Metadata/project_settings.config` as Bambu Studio and the Orca family write it.
    pub fn project_settings(self, printer_model: &str, printer_settings_id: &str) -> Self {
        let json = format!(
            "{{\"from\":\"project\",\"filament_colour\":[\"#FFFFFF\",\"#000000\"],\
             \"printer_model\":\"{printer_model}\",\
             \"printer_settings_id\":\"{printer_settings_id}\",\
             \"nozzle_diameter\":[\"0.4\"]}}"
        );
        self.entry("Metadata/project_settings.config", json.into_bytes())
    }

    pub fn raw_project_settings(self, bytes: &[u8]) -> Self {
        self.entry("Metadata/project_settings.config", bytes.to_vec())
    }

    /// `Metadata/Slic3r_PE.config` with PrusaSlicer's `; key = value` lines.
    pub fn prusa_config(self, printer_model: &str, printer_settings_id: &str) -> Self {
        let ini = format!(
            "; generated by PrusaSlicer 2.9.0 on 2026-01-01 at 00:00:00 UTC\n\n\
             ; layer_height = 0.2\n; printer_model = {printer_model}\n\
             ; printer_settings_id = {printer_settings_id}\n; printer_technology = FFF\n\
             ; printer_vendor =\n"
        );
        self.entry("Metadata/Slic3r_PE.config", ini.into_bytes())
    }

    pub fn entry(mut self, name: &str, bytes: Vec<u8>) -> Self {
        self.entries
            .push((name.to_owned(), bytes, CompressionMethod::Deflated));
        self
    }

    pub fn stored_entry(mut self, name: &str, bytes: Vec<u8>) -> Self {
        self.entries
            .push((name.to_owned(), bytes, CompressionMethod::Stored));
        self
    }

    pub fn write(self, dir: &Path, file_name: &str) -> PathBuf {
        let path = dir.join(file_name);
        let mut zip = ZipWriter::new(File::create(&path).unwrap());
        for (name, bytes, method) in self.entries {
            zip.start_file(
                name,
                SimpleFileOptions::default().compression_method(method),
            )
            .unwrap();
            zip.write_all(&bytes).unwrap();
        }
        zip.finish().unwrap();
        path
    }
}
